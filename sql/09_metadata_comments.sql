-- Every column with its type and description
CREATE OR REPLACE VIEW vw_metadata_columns AS
SELECT c.table_name, c.ordinal_position AS position, c.column_name, c.data_type, c.is_nullable, d.description
FROM information_schema.columns c
JOIN pg_catalog.pg_class k ON k.relname = c.table_name AND k.relnamespace = 'public'::regnamespace
LEFT JOIN pg_catalog.pg_description d ON d.objoid = k.oid AND d.objsubid = c.ordinal_position
WHERE c.table_schema = 'public' AND c.table_name IN ('dimmonth', 'dimdate', 'dimemployee', 'dimasset', 'dimsupplier', 'dimcustomermaster', 'dimiteminventory', 'dimwarehouseitem', 'factsales', 'factfinance', 'factmanufacturing', 'factaccountsreceivable', 'factprocurement', 'factwarehousesnapshot', 'factinventorydemand')
ORDER BY c.table_name, c.ordinal_position;

-- Every table with its description and size
CREATE OR REPLACE VIEW vw_metadata_tables AS
SELECT k.relname AS table_name, obj_description(k.oid, 'pg_class') AS description,
       (SELECT COUNT(*) FROM information_schema.columns c WHERE c.table_schema = 'public' AND c.table_name = k.relname) AS column_count
FROM pg_catalog.pg_class k
WHERE k.relnamespace = 'public'::regnamespace AND k.relkind = 'r' AND k.relname IN ('dimmonth', 'dimdate', 'dimemployee', 'dimasset', 'dimsupplier', 'dimcustomermaster', 'dimiteminventory', 'dimwarehouseitem', 'factsales', 'factfinance', 'factmanufacturing', 'factaccountsreceivable', 'factprocurement', 'factwarehousesnapshot', 'factinventorydemand')
ORDER BY k.relname;
